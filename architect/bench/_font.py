def _encode(rows: Sequence[str]) -> bytes:
    if len(rows) != GLYPH_HEIGHT or any(len(row) != GLYPH_WIDTH for row in rows):
        raise ValueError("Glyph art must be 8 x 13")
    out = bytearray()
    for row in rows:
        value = 0
        for column, cell in enumerate(row):
            if cell == "#":
                value |= 0x80 >> column
            elif cell != ".":
                raise ValueError("Glyph art uses only '#' and '.'")
        out.append(value)
    return bytes(out)


GLYPHS: dict[str, bytes] = {char: _encode(rows) for char, rows in _ART.items()}
if set(GLYPHS) != {chr(code) for code in range(0x20, 0x7F)}:  # pragma: no cover - data guard
    raise RuntimeError("GLYPHS must cover printable ASCII 0x20-0x7E exactly")


def draw_text(
    canvas: Sequence[bytearray], x: int, y: int, text: str, *, scale: int = 2, ink: int = 0
) -> None:
    """Blit ``text`` onto greyscale rows at (x, y); glyphs off the canvas are clipped."""
    height = len(canvas)
    width = len(canvas[0]) if height else 0
    for index, char in enumerate(text):
        glyph = GLYPHS.get(char, GLYPHS["?"])
        left = x + index * GLYPH_WIDTH * scale
        if left >= width:
            break
        for row_index, bits in enumerate(glyph):
            if not bits:
                continue
            segment = bytearray()
            for column in range(GLYPH_WIDTH):
                on = bits & (0x80 >> column)
                segment.extend((ink if on else 255,) * scale)
            for repeat in range(scale):
                row_y = y + row_index * scale + repeat
                if 0 <= row_y < height:
                    row = canvas[row_y]
                    for column, value in enumerate(segment):
                        target = left + column
                        if 0 <= target < width and value == ink:
                            row[target] = ink


